-- 박스 제목은 목록 이름 · 【…】 머리는 본문에 (기능/박스 §3.1, 2026-10-28).
-- 사용자 결정: 제목은 박스 목록에 보이는 이름일 뿐 본문과 관련 없다 — 약관에 찍히는 【…】 제목은 본문에 직접 넣는다.
--
-- 조립 · 미리보기는 이제 본문(줄)만 찍는다. 렌더 결과가 바뀌지 않게, 제목이 있는 박스는 본문 앞에 「【제목】」 줄을 넣는다.
-- 제목 칸은 그대로 둔다(이미 괄호 없는 이름 — 0032). 제목 없는 박스는 머리 줄이 없었으니 그대로.
-- 본문 첫 줄이 이미 「【제목】」이면 건너뛴다 — 두 번 돌려도 같다.
UPDATE "boxes" SET "lines" = jsonb_build_array('【' || "title" || '】') || "lines"
WHERE "title" <> '' AND ("lines"->>0) IS DISTINCT FROM ('【' || "title" || '】');
